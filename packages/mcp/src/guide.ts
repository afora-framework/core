/** A short guide to the afora.json format, for the agent (the resource afora://spec/guide). */
export const GUIDE = `# afora.json guide

\`afora.json\` describes a domain. \`afora_generate\` turns it into TypeScript on \`@afora/core\`
(one file per kind of declaration, under \`output.dir\`, default \`src/domain\`). The generated files
start with "// Generated by @afora/codegen from afora.json. Do not edit." and are overwritten on
every run, so change the JSON, never those files. To add behavior, extend the generated class in
a file of your own.

## Workflow

1. \`afora_catalog\`: what you can use (Std properties, record plugins, rules).
2. \`afora_spec_read\`: the current spec (or the one extracted from the code).
3. Edit with \`afora_spec_upsert\` / \`afora_spec_remove\` (one declaration at a time; the whole
   spec must stay valid, so declare what a declaration uses first) or \`afora_spec_write\`.
4. \`afora_spec_validate\`, then \`afora_generate\` (\`dryRun: true\` to preview). The result has the
   TypeScript diagnostics of the generated files: fix the spec until there are none.

## Shape

\`\`\`json
{
  "version": 1,
  "name": "blog",
  "output": { "dir": "src/domain" },
  "properties":   { "Age": { "base": "integer", "with": { "min": 0, "max": 150 } },
                    "Status": { "enum": ["draft", "published"] } },
  "blueprints":   { "Address": { "fields": { "street": "string", "zip": "string" } } },
  "records":      { "Money": { "fields": { "amount": "number", "currency": "string" } } },
  "entities":     { "User": { "fields": { "name": "text", "email": "email", "password": "password",
                                          "age": "Age?", "address": "Address", "tags": "string[]" },
                              "unique": ["email"], "change": ["name"] },
                    "Post": { "fields": { "title": "text", "status": "Status",
                                          "author": "User", "coauthors": "User[]" } } },
  "environments": { "Database": { "fields": { "DATABASE_URL": "url", "PORT": "integer" } } },
  "repositories": { "Users": { "entity": "User", "actions": ["findById", "findByEmail", "create", "update"],
                               "environments": ["Database"] },
                    "Posts": { "entity": "Post", "actions": ["findById", "findManyByAuthor", "create"],
                               "relations": ["Users"] } }
}
\`\`\`

## Fields

- Shorthand string: \`"email"\`, \`"Age?"\` (optional), \`"string[]"\` (list), \`"User[]?"\` (optional list).
- Lowercase names are Std properties (see \`afora_catalog\`: id, slug, email, phone, url, ip, password,
  string, text, number, integer, boolean, date, dateTime...). PascalCase names are declarations of
  the spec (properties, blueprints, records, entities).
- Object form: \`{ "type": "string", "optional": true, "list": { "minItems": 1, "maxItems": 5 }, "with": { "pattern": "^a" } }\`.
  \`with\` applies to each item of a list and only takes options valid for the type (min/max/pattern for strings,
  min/max/exclusiveMin/exclusiveMax/multipleOf for numbers, plus title/description/examples/deprecated/readOnly/writeOnly/default).
- Enum: \`{ "enum": ["a", "b"] }\`. Nested object in place: \`{ "fields": { "lat": "number", "lng": "number" } }\`.
- A property of your own: \`{ "base": "integer", "with": {...} }\`, \`{ "enum": [...] }\`, or
  \`{ "opaque": true, "import": "./my-property" }\` for a hand-written one (imported as it is).

## Rules the validator enforces

- Declaration names are PascalCase and unique across every kind; names exported by @afora/core are taken.
- No circular references between declarations (store an id instead of the entity).
- An entity cannot declare \`id\`, \`createdAt\`, \`updatedAt\`, \`deletedAt\` (it gets them). No record member names
  (\`toJSON\`, \`set\`, \`onSet\`...); see \`reservedRecordKeys\` in the catalog. \`blueprint\` and \`options\` are valid fields.
- \`unique\`, \`sensitive\`, \`change\` must name fields (or keys of its plugins); \`change\` cannot name an identity key.
  \`password\` is always sensitive and \`slug\` always unique; \`id\` is always unique.
- \`plugins\`: Std record plugins (publishable, archivable, taggable, ownable, authenticatable); their keys cannot be declared again.
- Repository actions: \`findById\`; \`findBy<Key>\` only for unique keys (id, \`unique\`, slug fields, unique plugin keys such as
  \`email\` of authenticatable); \`findManyBy<Key>\` only for keys that are not unique; \`create\`, \`update\`, \`delete\`, \`count\`.
- Repository \`deletion\`: \`"hard"\` (default) physically removes rows; \`"soft"\` retains \`deletedAt\` and hides deleted rows from reads, counts and relations.
- \`relations\` must list exactly one repository for each entity the repository's entity holds, at any depth (inside
  records, blueprints and nested objects), not through another entity.
- Environments hold properties only (no lists, no objects).
- \`extends\`: other specs (relative path to their afora.json, or a package) whose declarations you can reference;
  the same name for different declarations is a conflict. \`useCases\` is reserved (not supported yet).
`;
