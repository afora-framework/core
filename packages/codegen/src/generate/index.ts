type Json = unknown;

// ---------------------------------------------------------------- literals

function keyDoc(key: string): string {
	return isIdentifier(key) ? key : JSON.stringify(key);
}

/** A JSON value as a TypeScript literal: flat when it fits, broken when it does not. */
function literal(value: Json, onImport?: (reference: string) => string): Doc {
	if (onImport && isImportObject(value))
		return onImport(value.import as string);
	if (Array.isArray(value)) {
		if (value.length === 0) return "[]";
		return group([
			"[",
			indent([
				softline,
				join(
					[",", line],
					value.map((item) => literal(item, onImport)),
				),
			]),
			ifBreak(","),
			softline,
			"]",
		]);
	}
	if (typeof value === "object" && value !== null) {
		const entries = Object.entries(value).filter(([, v]) => v !== undefined);
		if (entries.length === 0) return "{}";
		return objectDoc(
			entries.map(([key, v]) => [key, literal(v, onImport)] as const),
			false,
			true,
		);
	}
	return JSON.stringify(value) ?? "undefined";
}

function objectDoc(
	props: readonly (readonly [key: string, value: Doc])[],
	expand = false,
	shorthand = false,
): Doc {
	if (props.length === 0) return "{}";
	return group(
		[
			"{",
			indent([
				line,
				join(
					[",", line],
					props.map(([key, value]) =>
						shorthand && value === key ? key : [keyDoc(key), ": ", value],
					),
				),
			]),
			ifBreak(","),
			line,
			"}",
		],
		expand,
	);
}

function call(callee: string, args: readonly Doc[]): Doc {
	return group([
		callee,
		"(",
		indent([softline, join([",", line], args)]),
		ifBreak(","),
		softline,
		")",
	]);
}

/** A call whose only argument is an object, which hugs the parentheses. */
function callWithObject(callee: string, object: Doc): Doc {
	return [callee, "(", object, ")"];
}

// ---------------------------------------------------------------- emitter

class Emitter {
	readonly core = new Set<string>();
	readonly local = new Map<string, Set<string>>();
	readonly extended = new Map<string, Set<string>>();
	readonly opaque: Doc[] = [];
	readonly opaqueImports = new Map<string, Map<string, string>>();

	constructor(
		readonly file: string,
		private readonly scope: Scope,
		private readonly fileOf: (name: string) => string,
	) {}

	use(name: string): string {
		this.core.add(name);
		return name;
	}

	/** The local name of `exported` imported from `module`, aliased when the name is taken. */
	bind(module: string, exported: string, taken: ReadonlySet<string>): string {
		const names = this.opaqueImports.get(module) ?? new Map<string, string>();
		this.opaqueImports.set(module, names);
		for (const [local, name] of names) if (name === exported) return local;
		const used = new Set<string>(taken);
		for (const imported of this.opaqueImports.values()) {
			for (const local of imported.keys()) used.add(local);
		}
		let local = exported;
		for (let n = 2; used.has(local); n++) local = `${exported}${n}`;
		names.set(local, exported);
		return local;
	}

	ref(name: string): string {
		const decl = this.scope.decls.get(name) as Decl;
		if (decl.via !== undefined) {
			const names = this.extended.get(decl.via) ?? new Set<string>();
			names.add(name);
			this.extended.set(decl.via, names);
			return name;
		}
		const file = this.fileOf(name);
		if (file !== this.file) {
			const names = this.local.get(file) ?? new Set<string>();
			names.add(name);
			this.local.set(file, names);
		}
		return name;
	}
}

interface Ctx {
	used: boolean;
}

function withOptions(options: unknown): Doc | undefined {
	if (typeof options !== "object" || options === null) return undefined;
	return Object.keys(options).length === 0 ? undefined : literal(options);
}

/** The property a field names, without optional or list. */
function itemDoc(field: Field, e: Emitter, ctx: Ctx): Doc {
	if (field.kind === "enum") {
		ctx.used = true;
		const options: [string, Doc][] = [];
		if (field.name !== undefined) options.push(["name", literal(field.name)]);
		if (field.default !== undefined) {
			options.push(["default", literal(field.default)]);
		}
		return call("ctx.enumOf", [
			literal([...field.values]),
			...(options.length > 0 ? [objectDoc(options)] : []),
		]);
	}
	if (field.kind === "inline") return blueprintDoc(field.fields, e, false);
	const options = withOptions(field.with);
	if (/^[a-z]/.test(field.type)) {
		ctx.used = true;
		return options
			? callWithObject(`ctx.${field.type}`, options)
			: `ctx.${field.type}`;
	}
	const name = e.ref(field.type);
	return options ? callWithObject(`${name}.with`, options) : name;
}

function fieldDoc(field: Field, e: Emitter, ctx: Ctx): Doc {
	const bounded = field.list && Object.keys(field.list).length > 0;
	const plain =
		field.kind === "type" &&
		/^[a-z]/.test(field.type) &&
		!field.with &&
		!bounded;
	if (plain && field.kind === "type") {
		ctx.used = true;
		const path = [
			field.list ? "list" : undefined,
			field.optional ? "optional" : undefined,
			field.type,
		].filter(Boolean);
		return ["ctx", ...path.map((part) => `.${part}`)];
	}
	let doc = itemDoc(field, e, ctx);
	if (field.list) {
		doc = call(e.use("listOf"), [
			doc,
			...(bounded
				? [
						objectDoc(
							Object.entries(field.list).map(
								([k, v]) => [k, literal(v)] as const,
							),
						),
					]
				: []),
		]);
	}
	if (field.optional) doc = call(e.use("optionalOf"), [doc]);
	return doc;
}

function blueprintDoc(
	fields: Readonly<Record<string, Field>>,
	e: Emitter,
	_environment: boolean,
): Doc {
	const ctx: Ctx = { used: false };
	const props = Object.entries(fields).map(
		([key, field]) => [key, fieldDoc(field, e, ctx)] as const,
	);
	const body: Doc =
		props.length === 0
			? "{}"
			: [
					"{",
					indent([
						hardline,
						join(
							[",", hardline],
							props.map(([key, value]) => [keyDoc(key), ": ", value]),
						),
					]),
					",",
					hardline,
					"}",
				];
	return [e.use("blueprintOf"), `((${ctx.used ? "ctx" : ""}) => (`, body, "))"];
}

// ---------------------------------------------------------------- declarations

function propertyDoc(decl: Decl, e: Emitter): Doc {
	const { spec } = decl;
	let expression: Doc;
	if (spec.opaque === true) {
		return "";
	}
	if (Array.isArray(spec.enum)) {
		const options: [string, Doc][] = [];
		if (spec.name !== undefined) options.push(["name", literal(spec.name)]);
		if (spec.default !== undefined) {
			options.push(["default", literal(spec.default)]);
		}
		expression = call(e.use("enumOf"), [
			literal(spec.enum),
			...(options.length > 0 ? [objectDoc(options)] : []),
		]);
	} else {
		const base = spec.base as string;
		const root = /^[a-z]/.test(base)
			? e.use((stdProperty(base) as { export: string }).export)
			: e.ref(base);
		const options = withOptions(spec.with);
		expression = options ? callWithObject(`${root}.with`, options) : root;
	}
	if (spec.optional === true) {
		expression = call(e.use("optionalOf"), [expression]);
	}
	return ["export const ", decl.name, " = ", expression, ";"];
}

function recordDoc(decl: Decl, e: Emitter): Doc {
	const entity = decl.kind === "entity";
	const fields = fieldsOfDecl(decl) as Record<string, Field>;
	const options: [string, Doc][] = [];
	for (const key of ["unique", "change", "sensitive"] as const) {
		const list = decl.spec[key];
		if (Array.isArray(list) && list.length > 0) {
			options.push([key, literal([...list].sort())]);
		}
	}
	const plugins = decl.spec.plugins;
	if (Array.isArray(plugins) && plugins.length > 0) {
		options.push([
			"plugins",
			[
				"(ctx) => ",
				group([
					"[",
					indent([
						softline,
						join(
							[",", line],
							plugins.map((p) => `ctx.${p}`),
						),
					]),
					ifBreak(","),
					softline,
					"]",
				]),
			],
		]);
	}
	const args: Doc[] = [blueprintDoc(fields, e, false)];
	if (options.length > 0) args.push(objectDoc(options, true));
	const maker = e.use(entity ? "entityOf" : "recordOf");
	return [
		"export class ",
		decl.name,
		" extends ",
		[
			maker,
			"(",
			indent([hardline, join([",", hardline], args)]),
			",",
			hardline,
			")",
		],
		" {}",
	];
}

function environmentDoc(decl: Decl, e: Emitter): Doc {
	const fields = fieldsOfDecl(decl) as Record<string, Field>;
	return [
		"export const ",
		decl.name,
		" = ",
		[
			e.use("environmentOf"),
			"(",
			indent([hardline, blueprintDoc(fields, e, true)]),
			",",
			hardline,
			")",
		],
		";",
	];
}

/** What provider expressions need: the catalog and the names an import must not take. */
interface Providers {
	readonly catalog: ReadonlyMap<string, ProviderCatalogEntry>;
	readonly taken: ReadonlySet<string>;
}

/** `inMemoryProvider()`, `drizzleProvider({ db })` or the imported provider. */
function providerDoc(value: unknown, e: Emitter, providers: Providers): Doc {
	const imported = (reference: string): string => {
		const { module, name } = parseImportRef(reference) as {
			module: string;
			name: string;
		};
		return e.bind(module, name, providers.taken);
	};
	if (isImportObject(value)) return imported(value.import as string);
	const { use, options } = value as {
		use: string;
		options?: Record<string, unknown>;
	};
	let factory: string;
	if (use === "inMemory") {
		factory = e.use("inMemoryProvider");
	} else {
		const entry = providers.catalog.get(use) as ProviderCatalogEntry;
		factory = e.bind(entry.module, entry.export, providers.taken);
	}
	return options && Object.keys(options).length > 0
		? callWithObject(factory, literal(options, imported))
		: `${factory}()`;
}

function repositoryDoc(decl: Decl, e: Emitter, providers: Providers): Doc {
	const { spec } = decl;
	const names = (list: unknown): string[] =>
		Array.isArray(list) ? (list as string[]) : [];
	const props: [string, Doc][] = [
		["entity", e.ref(spec.entity as string)],
		["actions", literal(names(spec.actions))],
	];
	if (spec.deletion === "soft") props.push(["deletion", literal("soft")]);
	if (spec.provider !== undefined) {
		props.push(["provider", providerDoc(spec.provider, e, providers)]);
	}
	const relations = names(spec.relations).map((name) => e.ref(name));
	if (relations.length > 0) props.push(["relations", listDoc(relations)]);
	const environments = names(spec.environments).map((name) => e.ref(name));
	if (environments.length > 0) {
		props.push(["environmentDependencies", listDoc(environments)]);
	}
	return [
		"export const ",
		decl.name,
		" = ",
		callWithObject(e.use("repositoryOf"), objectDoc(props, true)),
		";",
	];
}

/** A list of identifiers, such as `[Users, Posts]`. */
function listDoc(names: readonly string[]): Doc {
	return group([
		"[",
		indent([softline, join([",", line], names)]),
		ifBreak(","),
		softline,
		"]",
	]);
}

// ---------------------------------------------------------------- exceptions and use cases

function exceptionDoc(decl: Decl, e: Emitter): Doc {
	const layer = Object.entries(ExceptionLayers).find(
		([, value]) => value === decl.spec.layer,
	)?.[0] as string;
	const message =
		typeof decl.spec.message === "string"
			? decl.spec.message
			: defaultMessageOf(decl.name);
	return [
		"export const ",
		decl.name,
		" = ",
		callWithObject(
			e.use("exceptionOf"),
			objectDoc(
				[
					["layer", `${e.use("ExceptionLayers")}.${layer}`],
					["name", literal(decl.name)],
					["message", literal(message)],
				],
				true,
			),
		),
		";",
	];
}

/** `input`, `response` or `context`: a blueprint by name, or the blueprint of fields in place. */
function blueprintRefDoc(ref: unknown, e: Emitter): Doc {
	if (typeof ref === "string") return e.ref(ref);
	const fields = parseFields(
		(ref as { fields: unknown }).fields,
		[],
		[],
	) as Record<string, Field>;
	return blueprintDoc(fields, e, false);
}

/** A step as the class expression the TypeScript form takes: classes and functions in place of names. */
function stepDoc(
	step: Record<string, unknown>,
	e: Emitter,
	scope: Scope,
	providers: Providers,
): Doc {
	const props = Object.entries(step).map(([key, value]): [string, Doc] => {
		if (key === "build") return [key, e.ref(value as string)];
		if (key === "error" && Object.hasOwn(step, "ensure")) {
			const name = errorNameOf(value) as string;
			return [
				key,
				scope.decls.get(name)?.kind === "exception" ? e.ref(name) : e.use(name),
			];
		}
		if (key === "fn" && Object.hasOwn(step, "run")) {
			const { module, name } = parseImportRef(
				(value as { import: string }).import,
			) as { module: string; name: string };
			return [key, e.bind(module, name, providers.taken)];
		}
		return [key, literal(value)];
	});
	return objectDoc(props);
}

function useCaseDoc(
	decl: Decl,
	e: Emitter,
	scope: Scope,
	providers: Providers,
): Doc {
	const { spec } = decl;
	const props: [string, Doc][] = [
		["name", literal(decl.name)],
		["blueprint", blueprintRefDoc(spec.input, e)],
		["response", blueprintRefDoc(spec.response, e)],
	];
	if (spec.context !== undefined) {
		props.push(["context", blueprintRefDoc(spec.context, e)]);
	}
	const dependencies = Object.entries(
		(spec.dependencies as Record<string, string> | undefined) ?? {},
	);
	if (dependencies.length > 0) {
		props.push([
			"dependencies",
			objectDoc(
				dependencies.map(([key, name]) => [key, e.ref(name)] as const),
				false,
				true,
			),
		]);
	}
	const errors = ((spec.errors as string[] | undefined) ?? []).map((name) =>
		scope.decls.get(name)?.kind === "exception" ? e.ref(name) : e.use(name),
	);
	if (errors.length > 0) props.push(["errors", listDoc(errors)]);
	if (typeof spec.description === "string") {
		props.push(["description", literal(spec.description)]);
	}
	if (Array.isArray(spec.tags) && spec.tags.length > 0) {
		props.push(["tags", literal(spec.tags)]);
	}
	if (spec.deprecated === true) props.push(["deprecated", "true"]);
	const implementation = spec.implementation as {
		steps?: Record<string, unknown>[];
	};
	const maker = e.use("useCaseOf");
	if (implementation.steps) {
		const steps = implementation.steps;
		const docs = steps.map((step) => stepDoc(step, e, scope, providers));
		const forced =
			steps.length > 1 && steps.every((step) => Object.keys(step).length > 1);
		props.push([
			"steps",
			group(
				[
					"[",
					indent([softline, join([",", line], docs)]),
					ifBreak(","),
					softline,
					"]",
				],
				forced,
			),
		]);
		return [
			"export class ",
			decl.name,
			" extends ",
			callWithObject(maker, objectDoc(props, true)),
			" {}",
		];
	}
	return [
		"export abstract class ",
		`${decl.name}Base`,
		" extends ",
		callWithObject(maker, objectDoc(props, true)),
		" {}",
	];
}

// ---------------------------------------------------------------- files

function compareSpecifiers(a: string, b: string): number {
	// Case-insensitive on letters; at the first letter whose case differs, uppercase first.
	const length = Math.min(a.length, b.length);
	for (let i = 0; i < length; i++) {
		const x = a.charAt(i);
		const y = b.charAt(i);
		if (x === y) continue;
		const [lx, ly] = [x.toLowerCase(), y.toLowerCase()];
		if (lx !== ly) return lx < ly ? -1 : 1;
		return x === x.toUpperCase() ? -1 : 1;
	}
	return a.length - b.length;
}

function importDoc(names: Iterable<string>, from: string): Doc {
	const sorted = [...names].sort(compareSpecifiers);
	return group([
		"import {",
		indent([line, join([",", line], sorted)]),
		ifBreak(","),
		line,
		"} from ",
		JSON.stringify(from),
		";",
	]);
}

function exportFromDoc(names: Iterable<string>, from: string): Doc {
	return group([
		"export {",
		indent([line, join([",", line], [...names].sort(compareSpecifiers))]),
		ifBreak(","),
		line,
		"} from ",
		JSON.stringify(from),
		";",
	]);
}

/** Orders import sources as Biome does: packages, then `../`, then `./`. */
function compareSources(a: string, b: string): number {
	const rank = (source: string) =>
		source.startsWith("../") ? 1 : source.startsWith("./") ? 2 : 0;
	return rank(a) - rank(b) || (a < b ? -1 : a > b ? 1 : 0);
}

function pascalOf(text: string): string {
	return text
		.split(/[^A-Za-z0-9]+/)
		.filter(Boolean)
		.map((part) => part.charAt(0).toUpperCase() + part.slice(1))
		.join("");
}

/**
 * The files for `spec`, deterministic and formatted as Biome would: one
 * file for each kind of declaration (merged when kinds depend on each other),
 * `application.ts` with the `App`, and `index.ts`. Throws `InvalidSpecError`
 * if the spec does not validate. `extended` holds the specs it extends.
 */
export function generate(
	original: Spec,
	extended: Readonly<Record<string, ResolvedSpec>> = {},
	options: CodegenOptions = {},
): GeneratedFile[] {
	const issues = validateSpec(original, extended, options);
	if (issues.length > 0) throw new InvalidSpecError(issues);
	// The canonical form leaves out what a property or plugin already implies.
	const spec = normalizeSpec(original, extended);
	const input = spec as unknown as Record<string, unknown>;
	const scope = scopeOf(input, extended, []);
	const own = [...scope.decls.values()].filter(
		(decl) => decl.via === undefined,
	);
	const { order } = orderOf(own, scope);
	const dir = (spec.output?.dir ?? DEFAULT_OUTPUT_DIR)
		.replace(/^\.\//, "")
		.replace(/\/+$/, "");

	// One file for each kind, but kinds that need each other share the later file.
	const home = new Map<KindFile, KindFile>(
		(Object.values(FILE_OF_KIND) as KindFile[]).map((file) => [file, file]),
	);
	const resolveHome = (file: KindFile): KindFile => {
		let current = file;
		while (home.get(current) !== current)
			current = home.get(current) as KindFile;
		return current;
	};
	const needs = (from: KindFile, to: KindFile): boolean =>
		own.some(
			(decl) =>
				resolveHome(FILE_OF_KIND[decl.kind]) === from &&
				depsFiles(decl).some((file) => resolveHome(file) === to),
		);
	const depsFiles = (decl: Decl): KindFile[] => {
		const names =
			decl.kind === "property" ? [decl.spec.base] : namesUsedBy(decl);
		return names.flatMap((name) => {
			const dep = typeof name === "string" ? scope.decls.get(name) : undefined;
			return dep && dep.via === undefined ? [FILE_OF_KIND[dep.kind]] : [];
		});
	};
	const namesUsedBy = (decl: Decl): string[] => {
		if (decl.kind === "repository") {
			return [
				decl.spec.entity as string,
				...((decl.spec.relations as string[]) ?? []),
				...((decl.spec.environments as string[]) ?? []),
			];
		}
		const fields = fieldsOfDecl(decl);
		return fields ? typesUsed(fields) : [];
	};
	let merged = true;
	while (merged) {
		merged = false;
		for (const a of MERGE_ORDER) {
			for (const b of MERGE_ORDER) {
				if (a === b || resolveHome(a) === resolveHome(b)) continue;
				if (
					needs(resolveHome(a), resolveHome(b)) &&
					needs(resolveHome(b), resolveHome(a))
				) {
					const [early, late] =
						MERGE_ORDER.indexOf(resolveHome(a)) <
						MERGE_ORDER.indexOf(resolveHome(b))
							? [resolveHome(a), resolveHome(b)]
							: [resolveHome(b), resolveHome(a)];
					home.set(early, late);
					merged = true;
				}
			}
		}
	}
	const fileOf = (name: string): string =>
		resolveHome(FILE_OF_KIND[(scope.decls.get(name) as Decl).kind]);

	// Extended specs: where to import them from, and under which name their App.
	const takenNames = new Set(scope.decls.keys());
	const extendedInfo = new Map<string, { from: string; alias: string }>();
	for (const [index, [ref, resolved]] of [...scope.extended].entries()) {
		const outDir = resolved.spec.output?.dir ?? DEFAULT_OUTPUT_DIR;
		let from = ref;
		if (ref.startsWith(".")) {
			const specDir = ref.endsWith(".json") ? posix.dirname(ref) : ref;
			const target = posix.join(specDir, outDir.replace(/^\.\//, ""));
			const relative = posix.relative(dir || ".", target) || ".";
			from = relative.startsWith(".") ? relative : `./${relative}`;
		}
		const base =
			pascalOf(resolved.spec.name ?? posix.basename(ref, ".json")) ||
			`Extended${index + 1}`;
		let alias = `${base}App`;
		for (let n = 2; takenNames.has(alias); n++) alias = `${base}App${n}`;
		takenNames.add(alias);
		extendedInfo.set(ref, { from, alias });
	}

	const providers: Providers = {
		catalog: new Map(
			(options.providers ?? []).map((entry) => [entry.name, entry]),
		),
		taken: new Set([
			...catalog().reservedDeclarationNames,
			...takenNames,
			...own
				.filter((decl) => decl.kind === "useCase" && isImported(decl.spec))
				.map((decl) => `${decl.name}Base`),
		]),
	};

	const emitters = new Map<string, Emitter>();
	const bodies = new Map<string, Doc[]>();
	for (const decl of order) {
		const file = fileOf(decl.name);
		let e = emitters.get(file);
		if (!e) {
			e = new Emitter(file, scope, fileOf);
			emitters.set(file, e);
			bodies.set(file, []);
		}
		const body = bodies.get(file) as Doc[];
		if (decl.kind === "property" && decl.spec.opaque === true) {
			const exported = (decl.spec.ref as string | undefined) ?? decl.name;
			const mod = decl.spec.import as string;
			const names = e.opaqueImports.get(mod) ?? new Map<string, string>();
			names.set(decl.name, exported);
			e.opaqueImports.set(mod, names);
			body.push(["export { ", decl.name, " };"]);
			continue;
		}
		switch (decl.kind) {
			case "property":
				body.push(propertyDoc(decl, e));
				break;
			case "blueprint": {
				const fields = fieldsOfDecl(decl) as Record<string, Field>;
				body.push([
					"export const ",
					decl.name,
					" = ",
					blueprintDoc(fields, e, false),
					";",
				]);
				break;
			}
			case "record":
			case "entity":
				body.push(recordDoc(decl, e));
				break;
			case "environment":
				body.push(environmentDoc(decl, e));
				break;
			case "repository":
				body.push(repositoryDoc(decl, e, providers));
				break;
			case "exception":
				body.push(exceptionDoc(decl, e));
				break;
			case "useCase":
				body.push(useCaseDoc(decl, e, scope, providers));
				break;
		}
	}

	const importsOf = (e: Emitter): Doc[] => {
		const imports: [string, Doc][] = [];
		if (e.core.size > 0)
			imports.push(["@afora/core", importDoc(e.core, "@afora/core")]);
		for (const [file, names] of e.local) {
			const from = `./${file.replace(/\.ts$/, "")}`;
			imports.push([from, importDoc(names, from)]);
		}
		for (const [ref, names] of e.extended) {
			const info = extendedInfo.get(ref) as { from: string };
			imports.push([info.from, importDoc(names, info.from)]);
		}
		for (const [mod, names] of e.opaqueImports) {
			const specifiers = [...names].map(([local, exported]) =>
				local === exported ? local : `${exported} as ${local}`,
			);
			imports.push([mod, importDoc(specifiers, mod)]);
		}
		return imports
			.sort(([a], [b]) => compareSources(a, b))
			.map(([, doc]) => doc);
	};

	const out: GeneratedFile[] = [];
	const render = (name: string, imports: Doc[], body: Doc[]): void => {
		const doc: Doc = [
			BANNER,
			hardline,
			hardline,
			...(imports.length > 0
				? [join(hardline, imports), hardline, hardline]
				: []),
			join([hardline, hardline], body),
		];
		out.push({ path: posix.join(dir || ".", name), contents: print(doc) });
	};
	for (const name of GENERATED_FILES) {
		if (name === "application.ts" || name === "index.ts") continue;
		const e = emitters.get(name);
		if (e) render(name, importsOf(e), bodies.get(name) as Doc[]);
	}

	// application.ts
	const app = new Emitter("application.ts", scope, fileOf);
	const appName = typeof spec.name === "string" ? spec.name : "app";
	const props: (readonly [string, Doc])[] = [["name", literal(appName)]];
	if (scope.extended.size > 0) {
		props.push([
			"extends",
			listDoc(
				[...scope.extended.keys()].map(
					(ref) => (extendedInfo.get(ref) as { alias: string }).alias,
				),
			),
		]);
	}
	if (spec.provider !== undefined) {
		props.push(["provider", providerDoc(spec.provider, app, providers)]);
	}
	for (const [key, kind] of [
		["properties", "property"],
		["blueprints", "blueprint"],
		["records", "record"],
		["entities", "entity"],
		["environments", "environment"],
		["repositories", "repository"],
		["exceptions", "exception"],
		["useCases", "useCase"],
	] as const) {
		const entries = own
			.filter((decl) => decl.kind === kind)
			.map((decl) => decl.name)
			.sort()
			.map((name): readonly [string, Doc] => {
				const decl = scope.decls.get(name) as Decl;
				if (kind === "useCase" && isImported(decl.spec)) {
					// The hand-written class, imported under its own name when free.
					const { module, name: exported } = parseImportRef(
						(decl.spec.implementation as { import: string }).import,
					) as { module: string; name: string };
					const taken = new Set(providers.taken);
					taken.delete(name);
					return [name, app.bind(module, exported, taken)];
				}
				return [name, app.ref(name)];
			});
		if (entries.length > 0) {
			props.push([key, objectDoc(entries, false, true)]);
		}
	}
	const sortedAppImports = importsFor(app, extendedInfo);
	render("application.ts", sortedAppImports, [
		[
			"export const App = ",
			callWithObject("applicationOf", objectDoc(props, true)),
			";",
		],
	]);

	// index.ts
	const exportsList: [string, Doc][] = [];
	for (const name of GENERATED_FILES) {
		if (name === "index.ts") continue;
		if (name !== "application.ts" && !emitters.has(name)) continue;
		const from = `./${name.replace(/\.ts$/, "")}`;
		exportsList.push([from, ["export * from ", JSON.stringify(from), ";"]]);
	}
	const inheritedByRef = new Map<string, string[]>();
	for (const decl of scope.decls.values()) {
		if (decl.via === undefined) continue;
		inheritedByRef.set(decl.via, [
			...(inheritedByRef.get(decl.via) ?? []),
			decl.name,
		]);
	}
	for (const [ref, names] of inheritedByRef) {
		const info = extendedInfo.get(ref) as { from: string };
		exportsList.push([info.from, exportFromDoc(names, info.from)]);
	}
	const handlers = new Map<string, Set<string>>();
	for (const decl of own) {
		if (decl.kind !== "useCase" || !isImported(decl.spec)) continue;
		const { module, name } = parseImportRef(
			(decl.spec.implementation as { import: string }).import,
		) as { module: string; name: string };
		const names = handlers.get(module) ?? new Set<string>();
		names.add(name === decl.name ? name : `${name} as ${decl.name}`);
		handlers.set(module, names);
	}
	for (const [module, names] of handlers) {
		exportsList.push([module, exportFromDoc(names, module)]);
	}
	exportsList.sort(([a], [b]) => compareSources(a, b));
	out.push({
		path: posix.join(dir || ".", "index.ts"),
		contents: print([
			BANNER,
			hardline,
			hardline,
			join(
				hardline,
				exportsList.map(([, doc]) => doc),
			),
		]),
	});
	return out;
}

function typesUsed(fields: Readonly<Record<string, Field>>): string[] {
	const found: string[] = [];
	for (const field of Object.values(fields)) {
		if (field.kind === "type" && /^[A-Z]/.test(field.type))
			found.push(field.type);
		if (field.kind === "inline") found.push(...typesUsed(field.fields));
	}
	return found;
}

function importsFor(
	app: Emitter,
	extendedInfo: ReadonlyMap<string, { from: string; alias: string }>,
): Doc[] {
	const imports: [string, Doc][] = [];
	imports.push([
		"@afora/core",
		importDoc(new Set(["applicationOf", ...app.core]), "@afora/core"),
	]);
	for (const [mod, names] of app.opaqueImports) {
		const specifiers = [...names].map(([local, exported]) =>
			local === exported ? local : `${exported} as ${local}`,
		);
		imports.push([mod, importDoc(specifiers, mod)]);
	}
	for (const [file, names] of app.local) {
		const from = `./${file.replace(/\.ts$/, "")}`;
		imports.push([from, importDoc(names, from)]);
	}
	for (const [, info] of extendedInfo) {
		imports.push([info.from, importDoc([`App as ${info.alias}`], info.from)]);
	}
	return imports.sort(([a], [b]) => compareSources(a, b)).map(([, doc]) => doc);
}
