/** Thrown by `generate` for a spec that does not validate; the problems are in `issues`. */
export class InvalidSpecError extends Error {
	override readonly name = "InvalidSpecError";
	constructor(readonly issues: readonly SpecIssue[]) {
		super(
			`The spec is invalid:\n${issues
				.map((i) => `- ${i.path.join(".") || "(root)"}: ${i.message}`)
				.join("\n")}`,
		);
	}
}

