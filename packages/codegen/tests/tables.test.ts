import { describe, expect, test } from "bun:test";
import {
	generate,
	type ProviderCatalogEntry,
	type Spec,
	validateSpec,
} from "../src";

const drizzle = (
	dialect: string | readonly string[],
): ProviderCatalogEntry[] => [
	{
		name: "drizzle",
		module: "@afora/drizzle",
		export: "drizzleProvider",
		tables: { export: "drizzleTableOf", dialect },
	},
];

function spec(options: Record<string, unknown> = {}): Spec {
	return {
		version: 1,
		name: "app",
		output: { dir: "src/domain" },
		provider: {
			use: "drizzle",
			options: { db: { import: "./db.ts#db" }, ...options },
		},
		entities: {
			User: {
				fields: { name: "string", email: "email", age: "integer?" },
				unique: ["email"],
			},
			Post: { fields: { title: "string", author: "User" } },
		},
		repositories: {
			Users: {
				entity: "User",
				actions: ["create", "findMany"],
				indexes: { byAge: { where: ["age"], orderBy: "name" } },
			},
			Posts: { entity: "Post", actions: ["create"], relations: ["Users"] },
		},
	} as unknown as Spec;
}

const fileOf = (
	files: readonly { path: string; contents: string }[],
	name: string,
) => files.find((file) => file.path === `src/domain/${name}`)?.contents;

describe("tables of a catalog provider", () => {
	test("one dialect: schema.ts with a table per entity, given to the provider", () => {
		const files = generate(spec(), {}, { providers: drizzle("sqlite") });
		expect(
			fileOf(files, "schema.ts"),
		).toBe(`// Generated by @afora/codegen from afora.json. Do not edit.

import { drizzleTableOf } from "@afora/drizzle";
import { Post, User } from "./entities";

export const userTable = drizzleTableOf(User, {
	dialect: "sqlite",
	indexes: { byAge: { where: ["age"], orderBy: "name" } },
});

export const postTable = drizzleTableOf(Post, { dialect: "sqlite" });

/** The table of each entity, by name, for the provider. */
export const tables = { User: userTable, Post: postTable };
`);
		const application = fileOf(files, "application.ts") ?? "";
		expect(application).toContain('import { tables } from "./schema";');
		expect(application).toContain("drizzleProvider({ db, tables })");
		// Not re-exported: two dialects would export the same names.
		expect(fileOf(files, "index.ts")).not.toContain("./schema");
	});

	test("two dialects: schema.sqlite.ts and schema.pg.ts, and tables of your choice", () => {
		const providers = drizzle(["sqlite", "postgres"]);
		const issues = validateSpec(spec(), {}, { providers });
		expect(issues.map((issue) => [issue.code, issue.path.join("/")])).toEqual([
			["missing_provider_tables", "provider/options/tables"],
		]);
		const files = generate(
			spec({ tables: { import: "../tables.ts#tables" } }),
			{},
			{ providers },
		);
		expect(fileOf(files, "schema.ts")).toBeUndefined();
		expect(fileOf(files, "schema.sqlite.ts")).toContain(
			'drizzleTableOf(Post, { dialect: "sqlite" })',
		);
		expect(fileOf(files, "schema.pg.ts")).toContain(
			'drizzleTableOf(Post, { dialect: "postgres" })',
		);
		expect(fileOf(files, "application.ts")).toContain(
			'import { tables } from "../tables.ts";',
		);
	});

	test("a provider given its tables keeps them, and an import of schema.ts is no generated file", () => {
		const providers: ProviderCatalogEntry[] = [
			{ name: "drizzle", module: "@afora/drizzle", export: "drizzleProvider" },
		];
		const input = spec({ tables: { import: "./schema.ts#tables" } });
		expect(validateSpec(input, {}, { providers })).toEqual([]);
		const files = generate(input, {}, { providers });
		expect(fileOf(files, "schema.ts")).toBeUndefined();
		expect(fileOf(files, "application.ts")).toContain(
			'import { tables } from "./schema.ts";',
		);
	});

	test("only the entities stored through the provider get a table", () => {
		const input = spec() as unknown as {
			repositories: Record<string, Record<string, unknown>>;
		};
		input.repositories.Posts = {
			...input.repositories.Posts,
			provider: "inMemory",
		};
		const files = generate(
			input as unknown as Spec,
			{},
			{
				providers: drizzle("postgres"),
			},
		);
		const schema = fileOf(files, "schema.ts") ?? "";
		expect(schema).toContain("drizzleTableOf(User");
		expect(schema).not.toContain("drizzleTableOf(Post");
	});

	test("refuses a malformed tables entry of the catalog", () => {
		for (const tables of [
			{ export: "drizzle table", dialect: "sqlite" },
			{ export: "drizzleTableOf", dialect: [] },
			{ export: "drizzleTableOf", dialect: ["sqlite", "sqlite"] },
			{ export: "drizzleTableOf", dialect: "sqlite", module: "" },
			"drizzleTableOf",
		]) {
			const providers = [
				{
					name: "drizzle",
					module: "@afora/drizzle",
					export: "drizzleProvider",
					tables,
				},
			] as unknown as ProviderCatalogEntry[];
			expect(
				validateSpec(spec(), {}, { providers }).map((issue) => issue.code),
			).toContain("invalid_provider_catalog");
		}
	});
});
