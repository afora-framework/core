/**
 * Generates docs/reference/api.md from the JSDoc of the built `.d.ts` of the
 * four entries: one section per entry, one `### Name` per export (sorted)
 * with its kind, tier, import line and JSDoc (summary, @param, @returns,
 * @throws, @default, @deprecated, @example). Deterministic. Needs `dist/`:
 * run `bun run build` first.
 *
 *   bun scripts/gen-api-reference.ts          write the file
 *   bun scripts/gen-api-reference.ts --check  exit 1 when the file differs
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import {
	builtExports,
	type ExportInfo,
	root,
	stripFences,
	type Tier,
} from "../tests/api-surface/program";

const target = join(root, "docs/reference/api.md");

const tierText: Record<Tier, string> = {
	stable: "stable",
	adapters: "adapters",
	experimental: "experimental (may change in any release)",
	testing: "testing",
};

function render(): string {
	const out: string[] = [
		"# API reference",
		"",
		"<!-- Generated by `bun run docs:api` from the JSDoc of the built package. Do not edit by hand: change the JSDoc in `src/` and regenerate. -->",
		"",
		"Every export of `@afora/core`, by entry point, with its description and examples. The tier says what [VERSIONING.md](../../VERSIONING.md) promises about it; [API tiers](../api-tiers.md) explains how a name gets one. Concepts and guides are in the [docs index](../README.md).",
		"",
	];
	for (const { entry, exports } of builtExports()) {
		out.push(`## ${entry.specifier}`, "");
		out.push(`Tier: ${tierText[entry.tier]}. ${exports.length} exports.`, "");
		for (const info of exports) out.push(...renderExport(info, entry));
	}
	return `${collapseBlankLines(out.join("\n")).trimEnd()}\n`;
}

/** Collapses runs of blank lines in prose only; fenced blocks stay verbatim. */
function collapseBlankLines(text: string): string {
	return text
		.split(/(^```[^\n]*\n[\s\S]*?\n```$)/m)
		.map((part, i) => (i % 2 ? part : part.replace(/\n{3,}/g, "\n\n")))
		.join("");
}

function renderExport(
	info: ExportInfo,
	entry: { specifier: string; tier: Tier },
): string[] {
	const typeOnly = !info.isValue;
	const lines = [
		`### ${info.name}`,
		"",
		`*${info.kind}* · tier: ${entry.tier} · \`import ${typeOnly ? "type " : ""}{ ${info.name} } from "${entry.specifier}"\``,
		"",
	];
	if (info.summary.trim()) lines.push(info.summary.trim(), "");
	const tag = (name: string) => info.tags.filter((t) => t.name === name);

	const params = tag("param");
	if (params.length) {
		lines.push("**Parameters**", "");
		for (const { text } of params) {
			const [name = "", ...rest] = text.trim().split(/\s+/);
			lines.push(
				`- \`${name}\`${rest.length ? `: ${rest.join(" ").replace(/^-\s*/, "")}` : ""}`,
			);
		}
		lines.push("");
	}
	for (const { text } of tag("returns"))
		lines.push(`**Returns** ${text.trim()}`, "");
	for (const { text } of tag("throws"))
		lines.push(`**Throws** ${text.trim()}`, "");
	for (const { text } of tag("default"))
		lines.push(`**Default** ${text.trim()}`, "");
	for (const { text } of tag("deprecated"))
		lines.push(`**Deprecated** ${text.trim()}`, "");
	for (const { text } of tag("example"))
		lines.push("**Example**", "", "```ts", stripFences(text), "```", "");
	return lines;
}

const content = render();
if (process.argv.includes("--check")) {
	const current = existsSync(target) ? readFileSync(target, "utf8") : "";
	if (current !== content) {
		console.error(
			"docs/reference/api.md is out of date: regenerate with `bun run docs:api`.",
		);
		process.exit(1);
	}
	console.log("docs/reference/api.md is up to date.");
} else {
	mkdirSync(dirname(target), { recursive: true });
	writeFileSync(target, content);
	console.log(`Wrote ${target}`);
}
