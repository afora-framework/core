// Turns a report (results/latest.json) into RESULTS.md.
import { GUARDED, LIBRARIES, REFERENCE } from "./contenders.ts";
import { GUARD_DEFAULT, GUARD_LIMITS } from "./guard.limits.ts";
import type { Row, RuntimeReport, Table } from "./harness.ts";
import type { Footprint } from "./size.ts";

export type Report = {
	/**
	 * Version of this format; a change that breaks a reader raises it. 2:
	 * `runs` may hold several Node runs, told apart by `version`, and the keys
	 * of `Footprint.cold` are those versions instead of `bun` and `node`.
	 * Everything here reads both.
	 */
	schema: 1 | 2;
	generatedAt: string;
	/** Version of afora in package.json and the commit that was measured. */
	afora: { version: string; commit: string };
	/** Installed version of each library, by its key in `LIBRARIES`. */
	libraries: Record<string, string>;
	/** One per runtime; times are nanoseconds per call. */
	runs: RuntimeReport[];
	footprints: Footprint[];
};

const fmtOps = (avgNs: number) => {
	const ops = 1e9 / avgNs;
	if (ops >= 1e6) return `${(ops / 1e6).toFixed(2)}M`;
	return ops >= 1e3 ? `${(ops / 1e3).toFixed(1)}k` : ops.toFixed(0);
};
const fmtNs = (ns: number) => {
	if (ns >= 1e6) return `${(ns / 1e6).toFixed(2)} ms`;
	if (ns >= 1e4) return `${(ns / 1e3).toFixed(1)} µs`;
	return ns >= 1000 ? `${ns.toFixed(0)} ns` : `${ns.toFixed(1)} ns`;
};
const fmtKb = (bytes: number) => `${(bytes / 1024).toFixed(1)} kB`;
/** The major version of a run's runtime: 24 for "Node v24.11.0". */
const majorOf = (run: RuntimeReport) =>
	Number.parseInt(run.version.replace(/^\D+/, ""), 10) || 0;

/** The short name of a run, "Bun" or "Node 24": a report can hold several Node runs. */
const runtimeName = (run: RuntimeReport) =>
	run.runtime === "bun" ? "Bun" : `Node ${majorOf(run)}`;

/** "a", "a and b", "a, b and c". */
const listed = (items: string[]) =>
	items.length < 2
		? (items[0] ?? "")
		: `${items.slice(0, -1).join(", ")} and ${items.at(-1)}`;

/** Whether two rows are too close to call: their confidence intervals overlap. */
export const tied = (a: Row, b: Row) =>
	Math.abs(a.avg - b.avg) <= a.avg * a.margin + b.avg * b.margin;

function resultTable(table: Table): string[] {
	const rows = [...table.rows].sort((a, b) => a.avg - b.avg);
	const fastest = rows[0] as Row;
	const out = [
		"| Contender | ops/s | mean | p75 | p99 | ± | vs fastest |",
		"| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
	];
	for (const row of rows) {
		const label = row.note ? `${row.contender} (${row.note})` : row.contender;
		let relative = `${(row.avg / fastest.avg).toFixed(1)}x slower`;
		if (row === fastest) relative = "fastest";
		else if (tied(row, fastest)) relative = "tied with the fastest";
		out.push(
			`| ${label} | ${fmtOps(row.avg)} | ${fmtNs(row.avg)} | ${fmtNs(row.p75)} | ${fmtNs(row.p99)} | ${(row.margin * 100).toFixed(1)}% | ${relative} |`,
		);
	}
	return out;
}

export function renderResults(report: Report): string {
	const scenarios = new Map<string, Table>();
	for (const table of report.runs[0]?.tables ?? []) {
		if (!scenarios.has(table.scenario)) scenarios.set(table.scenario, table);
	}
	const runtimes = report.footprints[0]
		? Object.keys(report.footprints[0].cold)
		: [];

	const out: string[] = [
		"# Benchmark results",
		"",
		"Generated by `bun run bench` from `bench/results/latest.json`; do not edit by hand. How it is measured, what each row does and how to contest a row are in [README.md](README.md).",
		"",
		`afora ${report.afora.version} (\`${report.afora.commit}\`), measured on ${report.generatedAt.slice(0, 10)}. Times are per call, on an already-built schema. They vary by machine, so compare rows within a table, not across machines.`,
		"",
		"## Machine",
		"",
		...report.runs.map((run) => `- ${run.version}, ${run.os}, CPU: ${run.cpu}`),
		"",
		"## Libraries",
		"",
		"| Library | Version |",
		"| --- | --- |",
		...Object.entries(report.libraries).map(
			([key, version]) => `| ${LIBRARIES[key]?.label ?? key} | ${version} |`,
		),
		"",
		"## Scenarios",
		"",
		"The same data shape for every library, objects that reject undeclared keys everywhere, and every error collected (no library stops at the first one).",
		"",
		...[...scenarios.values()].map(
			(table) => `- **${table.title}** (\`${table.scenario}\`): ${table.shape}`,
		),
		"",
	];

	for (const run of report.runs) {
		out.push(`## Results on ${run.version}`, "");
		for (const table of run.tables) {
			out.push(
				`### ${table.title}, ${table.case} input (${runtimeName(run)})`,
				"",
				...resultTable(table),
				"",
			);
		}
	}

	if (report.footprints.length > 0) {
		out.push(
			"## Bundle size and cold start",
			"",
			"Each library validating the flat object, bundled by itself (minified, `bun build`); the files are in `bench/entries/`. Cold start is the time a new process takes to import that bundle, which loads the library, builds the schema and validates once (median of 15 processes).",
			"",
			`| Library | min | gzip | ${runtimes.map((runtime) => `cold start (${runtime})`).join(" | ")} |`,
			`| --- | ---: | ---: | ${runtimes.map(() => "---:").join(" | ")} |`,
			...[...report.footprints]
				.sort((a, b) => a.gzip - b.gzip)
				.map(
					(row) =>
						`| ${LIBRARIES[row.library]?.label ?? row.library} | ${fmtKb(row.min)} | ${fmtKb(row.gzip)} | ${runtimes.map((runtime) => `${(row.cold[runtime] ?? 0).toFixed(1)} ms`).join(" | ")} |`,
				),
			"",
			"afora is a framework with one entry point: its bundle carries TypeBox and the code of records, entities, repositories and use cases, whatever the file uses. Typia is small because its validator is generated at build time; Valibot because it is made to be tree-shaken.",
			"",
		);
	}

	const limits = Object.entries(GUARD_LIMITS);
	out.push(
		"## What CI holds",
		"",
		`\`bun run bench:guard\` times \`${GUARDED.replace("afora ", "")}\` and ${REFERENCE} on every case above, several times each in one process, and fails when the best time of afora is over the limit of the case, as a multiple of the best time of Zod 4. The limit is ${GUARD_DEFAULT}x${limits.length > 0 ? ", except:" : "."}`,
		"",
		...limits.map(
			([name, { limit, why }]) => `- \`${name}\`: ${limit}x. ${why}`,
		),
		"",
	);
	return out.join("\n");
}

// ------------------------------------------------------------- README
/** The row of afora that does what the other libraries do. */
const HEADLINE = GUARDED;
/** The scenario and case of the chart: the body of a request, valid. */
const CHART = { scenario: "api-payload", case: "valid" } as const;

/** The run the README leads with: the newest Node when one was measured, as most servers run on Node. */
const leadRun = (report: Report) =>
	report.runs
		.filter((run) => run.runtime === "node")
		.sort((a, b) => majorOf(b) - majorOf(a))[0] ?? report.runs[0];

/** The first row of each library in a table (for afora, the headline row). */
function rowsByLibrary(table: Table): Map<string, Row> {
	const rows = new Map<string, Row>();
	for (const row of table.rows) {
		if (row.library === "afora" && row.contender !== HEADLINE) continue;
		if (!rows.has(row.library)) rows.set(row.library, row);
	}
	return rows;
}

function summaryTable(run: RuntimeReport): string[] {
	const libraries = Object.keys(LIBRARIES).filter((key) => key !== "afora");
	const out = [
		`| ${runtimeName(run)} | afora | ${libraries.map((key) => LIBRARIES[key]?.label).join(" | ")} |`,
		`| --- | ---: | ${libraries.map(() => "---:").join(" | ")} |`,
	];
	for (const table of run.tables) {
		const rows = rowsByLibrary(table);
		const afora = rows.get("afora");
		if (!afora) continue;
		const cells = libraries.map((key) => {
			const row = rows.get(key);
			return row ? `${(row.avg / afora.avg).toFixed(2)}x` : "";
		});
		out.push(
			`| ${table.title}, ${table.case} | ${fmtNs(afora.avg)} | ${cells.join(" | ")} |`,
		);
	}
	return out;
}

/** The block of README.md between `<!-- bench:start -->` and `<!-- bench:end -->`. */
export function renderSummary(report: Report): string {
	const lead = leadRun(report);
	if (!lead) return "";
	const others = report.runs.filter((run) => run !== lead);
	return [
		`![Validations per second on the body of an API request, ${lead.version}](bench/results/chart.svg)`,
		"",
		`Time of each library as a multiple of afora \`blueprint.safeParse\` on the same case: above 1.00x it is slower than afora, below it is faster. TypeBox, Ajv and Typia only check, they do not transform. afora ${report.afora.version}, ${listed(report.runs.map((run) => run.version))}, ${lead.cpu}; generated from \`bench/results/latest.json\`.`,
		"",
		...summaryTable(lead),
		...others.flatMap((run) => ["", ...summaryTable(run)]),
	].join("\n");
}

const escapeXml = (text: string) =>
	text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/** Horizontal bars of validations per second, one per library, afora in the accent. */
export function renderChart(report: Report): string {
	const run = leadRun(report);
	const table = run?.tables.find(
		(candidate) =>
			candidate.scenario === CHART.scenario && candidate.case === CHART.case,
	);
	if (!run || !table) return "";
	const rows = [...rowsByLibrary(table).entries()]
		.map(([library, row]) => ({ library, row, ops: 1e9 / row.avg }))
		.sort((a, b) => b.ops - a.ops);
	const max = Math.max(...rows.map((entry) => entry.ops));

	const width = 760;
	const labelWidth = 150;
	const valueWidth = 190;
	const barMax = width - labelWidth - valueWidth;
	const barHeight = 18;
	const step = 30;
	const top = 56;
	const height = top + rows.length * step + 34;

	const bars = rows.map(({ library, row, ops }, index) => {
		const y = top + index * step;
		const length = Math.max(2, (ops / max) * barMax);
		const radius = Math.min(4, length / 2);
		const checksOnly = row.note?.includes("no transforms");
		const name = LIBRARIES[library]?.label ?? library;
		// A bar with a square start on the baseline and a rounded data-end.
		const path = `M${labelWidth},${y} h${length - radius} a${radius},${radius} 0 0 1 ${radius},${radius} v${barHeight - 2 * radius} a${radius},${radius} 0 0 1 -${radius},${radius} h-${length - radius} z`;
		return [
			`<text class="${library === "afora" ? "name strong" : "name"}" x="${labelWidth - 10}" y="${y + 13}" text-anchor="end">${escapeXml(name)}</text>`,
			`<path class="${library === "afora" ? "bar accent" : "bar"}" d="${path}"/>`,
			`<text class="value" x="${labelWidth + length + 8}" y="${y + 13}">${fmtOps(row.avg)} ops/s${checksOnly ? '<tspan class="muted"> · checks only</tspan>' : ""}</text>`,
		].join("\n");
	});

	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}" role="img" aria-labelledby="title desc" font-family="ui-sans-serif, system-ui, -apple-system, 'Segoe UI', sans-serif">
<title id="title">Validations per second: ${escapeXml(table.title)}, ${table.case} input</title>
<desc id="desc">${rows.map(({ library, row }) => `${LIBRARIES[library]?.label ?? library}: ${fmtOps(row.avg)} per second`).join("; ")}.</desc>
<style>
	.title { font-size: 15px; font-weight: 600; fill: #0b0b0b; }
	.subtitle, .foot { font-size: 12px; fill: #52514e; }
	.name { font-size: 13px; fill: #52514e; }
	.name.strong { font-weight: 600; fill: #0b0b0b; }
	.value { font-size: 12px; fill: #0b0b0b; font-variant-numeric: tabular-nums; }
	.muted { fill: #52514e; }
	.bar { fill: #a3a29c; }
	.bar.accent { fill: #2a78d6; }
	.axis { stroke: #a3a29c; stroke-width: 1; }
	@media (prefers-color-scheme: dark) {
		.title, .name.strong, .value { fill: #f0efec; }
		.subtitle, .foot, .name, .muted { fill: #c3c2b7; }
		.bar { fill: #6b6a65; }
		.bar.accent { fill: #3987e5; }
		.axis { stroke: #6b6a65; }
	}
</style>
<text class="title" x="0" y="18">Validations per second, ${escapeXml(table.title.replace(/^API/, "API"))}</text>
<text class="subtitle" x="0" y="38">Valid input, every rule and transform applied; longer is faster. ${escapeXml(run.version)}, ${escapeXml(run.cpu)}.</text>
<line class="axis" x1="${labelWidth}" y1="${top - 6}" x2="${labelWidth}" y2="${top + rows.length * step - 6}"/>
${bars.join("\n")}
<text class="foot" x="0" y="${height - 8}">afora ${escapeXml(report.afora.version)} blueprint.safeParse. "Checks only": the library has no transforms and gets the already-clean value.</text>
</svg>
`;
}

const START = "<!-- bench:start -->";
const END = "<!-- bench:end -->";

/** `readme` with its generated block replaced. */
export function withSummary(readme: string, report: Report): string {
	const start = readme.indexOf(START);
	const end = readme.indexOf(END);
	if (start === -1 || end === -1) {
		throw new Error(`README.md has no ${START} ... ${END} block.`);
	}
	return `${readme.slice(0, start + START.length)}\n\n${renderSummary(report)}\n\n${readme.slice(end)}`;
}

/** What a formatter may change in Markdown: the padding of a table and the length of its rules. */
export const normalized = (markdown: string) =>
	markdown
		.replace(/[ \t]+/g, " ")
		.replace(/-{2,}/g, "-")
		.replace(/ ?\| ?/g, "|")
		.trim();
